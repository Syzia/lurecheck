"""Write docs/results.md from a fresh measurement. Run: python tools/write_results.py

The prose is here; every number comes from lurecheck.evaluate, and a test
(tests/test_results_doc.py) fails if the document and the code drift apart.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lurecheck.checks import Options  # noqa: E402
from lurecheck.evaluate import (PUBLISHED_SEEDS, findings_table, headline, run, scenario_table, summary_table,  # noqa: E402
                                sweep_table)  # fmt: skip
from lurecheck.simulator import PROTECTED, SCENARIOS, generate  # noqa: E402


def document() -> str:
    outcomes = run(generate(PUBLISHED_SEEDS), Options(protected=PROTECTED))
    phish = sum(s.label == "phish" for s in SCENARIOS)
    return f"""# Measured results

How often Lurecheck flags phishing, and how often it flags legitimate mail, measured on labelled messages rather than asserted.

**Read this first.** These are *simulated* messages, written by the same person who wrote the checks, so high scores on the scenarios it was built for prove little. And every scenario turns out to be caught every time or never: the details that change between runs (names, wording, addresses) never change the outcome. The headline percentages below are therefore mostly a count of scenarios, and the mix of scenarios was chosen, not sampled from anyone's inbox. **The scenario table is the result; the percentages are a summary of it.** Lurecheck has not yet been measured on real email.

## How it is measured

- **{len(SCENARIOS)} scenarios**, {phish} phishing and {len(SCENARIOS) - phish} legitimate, each written {len(PUBLISHED_SEEDS)} times with different details (seeds 1 to {len(PUBLISHED_SEEDS)}): {len(outcomes)} messages. They are generated by `lurecheck/simulator.py`.
- Each one is a complete email, read and scored by exactly the code that reads a real file.
- The reader's own bank, `northwind-bank.example`, is protected, as `--protect` would do for a real reader's organisation.
- A message counts as **flagged** when its score reaches 20, the "suspicious" band.
- **Seven scenarios are documented exceptions**: four phishing messages Lurecheck is expected to miss, and three legitimate ones it is expected to flag. They are in the measurement on purpose. Leaving out what a tool gets wrong is the easiest way to make it look good.

## Results at the shipped settings

{summary_table(outcomes)}

{headline(outcomes)}

What this says:

- **Every message was handled as documented**, including the known misses and false alarms.
- **Seven of the eleven phishing scenarios are flagged every time.** The other four are the documented misses, explained below.
- **Three of the eight legitimate scenarios are flagged every time**, all of them documented false alarms. They are over-represented on purpose: three in eight is not the share of real mail that is click-tracked newsletters, help-desk tickets and mailing lists, which could be higher or lower depending on the inbox.
- **Nothing legitimate reached "likely phishing"** (50 or more). The false alarms all sit in the "suspicious" band.

## Scenario by scenario

{scenario_table(outcomes)}

## What it gets wrong

**Phishing it misses:**

- `shortened-link` scores 10, under the line. A shortener hides the destination, and Lurecheck never follows a link to find out where it goes.
- `plain-phish` scores nothing. It comes from the attacker's own new domain, passes every authentication check, and links only to that domain. There is no technical tell; only the wording, or the age of the domain, would give it away.
- `gift-card-request` scores nothing. A request for gift cards from a free mail account is pure social engineering, and Lurecheck does not judge wording.
- `html-attachment` scores nothing, because attachments are not examined until stage 5.

**Legitimate mail it flags:**

- `tracked-newsletter` (25): click tracking sends every link through the mailing service's own address. A link whose text reads `www.company.example` and whose address goes to the tracker is, mechanically, what a deceptive link is.
- `help-desk` (25): replies go to the help-desk service's domain instead of the company's. That is how help desks work, and how a forged sender collects the victim's answer.
- `mailing-list` (40): the list adds a footer, which breaks the author's signature, so DMARC fails for the author's domain exactly as it would for a forgery.

Each of the three is a real phishing signal that cannot tell its innocent twin apart without more information than the message holds. That is why none of them scores above "suspicious" on its own.

## Where to draw the line

The same messages, flagged from different scores:

{sweep_table(outcomes)}

- **At 30**, two of the three false alarms disappear, and so does `ip-link`: a phishing link to a bare numeric address (25) is no longer flagged.
- **At 50**, nothing legitimate is flagged, and fewer than half of the phishing messages are. The display-name trick (35) and the numeric link (25) both fall under the line.
- **At 10**, the shortened link is caught, and so is the bank's genuine mail from its second domain (10).

The shipped line, 20, was chosen before measuring and has not been moved. These numbers show what moving it would trade. Where it should sit for real mail depends on how much of that mail looks like the three false alarms, which simulated data cannot say.

## Which findings fire on legitimate mail

{findings_table(outcomes)}

- Three findings fire more often on legitimate mail than on phishing in this mix: `auth.dmarc-fail`, `link.text-shows-another-site` and `sender.reply-goes-elsewhere`. They are the causes of the three false alarms.
- The lookalike findings never fire on legitimate mail here, with one exception: the bank's second domain is the same name under a different ending, which scores 10 and stays under the line.

## What measuring changed

The first run found two problems, and both were fixed before these numbers were produced:

- **A false alarm in Lurecheck.** The bank's genuine mail from a second domain it owns scored 35, because the same fact was counted twice: once as a different ending, and again as a sender name claiming the bank. The brand-name check now stands aside when the sending domain *is* the brand's name under another ending.
- **A bug in the generator.** One of the lookalike links replaced a letter with a foreign one that does not resemble it, so it was not a lookalike at all.

Nothing else was tuned to these results.

## Your own email

The same tables, for real messages you have saved:

```bash
python -m lurecheck.evaluate --folder ~/phishing-samples --protect your-organisation.example
```

Put phishing in `~/phishing-samples/phish/` and legitimate mail in `~/phishing-samples/benign/`, any folders deep. The tables contain only counts and finding ids, never an address, a subject or any other text from a message, so they are safe to share. The messages themselves are not: keep them out of this repository.

## Reproduce

```bash
python -m lurecheck.evaluate --published
```

A test (`tests/test_results_doc.py`) regenerates every table on this page and fails if the page is out of date. The page itself is written by `python tools/write_results.py`.
"""


if __name__ == "__main__":
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "docs", "results.md")
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(document())
    print(f"wrote {path}")
